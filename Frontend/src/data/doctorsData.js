/**
 * Normalizes doctor name string for robust matching
 */
const cleanName = (str) => {
  if (!str) return "";
  return str.toLowerCase().replace(/dr\.?|prof\.?|surgeon|md|mbbs/g, "").replace(/[^a-z0-9]/g, "").trim();
};

/**
 * Universal resolver that maps ANY doctor (from backend, prop, or string)
 * to their exact verified local asset image. NEVER falls back to an unknown stock photo.
 */
export const getDoctorAvatar = (doctorOrIdOrName) => {
  if (!doctorOrIdOrName) return doctorImg1;

  // If already an imported asset URL (ends with .png, .jpg or data:)
  if (typeof doctorOrIdOrName === "string" && (doctorOrIdOrName.startsWith("/assets/") || doctorOrIdOrName.startsWith("data:") || doctorOrIdOrName.includes("Doctor-img") || doctorOrIdOrName.includes("New-Doctor-img"))) {
    return doctorOrIdOrName;
  }

  // Check by ID if numeric or provided as object
  let targetId = null;
  let targetName = null;

  if (typeof doctorOrIdOrName === "number") {
    targetId = doctorOrIdOrName;
  } else if (typeof doctorOrIdOrName === "string") {
    const parsed = parseInt(doctorOrIdOrName, 10);
    if (!isNaN(parsed) && String(parsed) === doctorOrIdOrName.trim()) {
      targetId = parsed;
    } else {
      targetName = doctorOrIdOrName;
    }
  } else if (typeof doctorOrIdOrName === "object") {
    targetId = doctorOrIdOrName.id;
    targetName = doctorOrIdOrName.user?.name || doctorOrIdOrName.name;
    // If it already has an imageUrl that is a valid asset
    if (doctorOrIdOrName.imageUrl && typeof doctorOrIdOrName.imageUrl === "string" && !doctorOrIdOrName.imageUrl.includes("unsplash")) {
      return doctorOrIdOrName.imageUrl;
    }
    if (doctorOrIdOrName.image && typeof doctorOrIdOrName.image === "string" && !doctorOrIdOrName.image.includes("unsplash")) {
      return doctorOrIdOrName.image;
    }
  }

  // 1. Direct match by ID (1 to 14)
  if (targetId) {
    const foundById = CANONICAL_DOCTORS.find(d => d.id === Number(targetId));
    if (foundById) return foundById.imageUrl;
  }

  // 2. Match by clean doctor name
  if (targetName) {
    const needle = cleanName(targetName);
    const foundByName = CANONICAL_DOCTORS.find(d => {
      const haystack = cleanName(d.name);
      return haystack.includes(needle) || needle.includes(haystack);
    });
    if (foundByName) return foundByName.imageUrl;
  }

  // Default fallback to Dr. Ananya Sharma's authentic portrait
  return doctorImg1;
};

